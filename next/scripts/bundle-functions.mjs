// One file per Edge Function, for the Supabase dashboard editor (Edwin deploys by paste,
// there is no Supabase CLI on the Mac). The editor cannot follow imports into ../_shared or
// next/src/lib, so this bundles each function into supabase/functions/<name>/bundled.ts.
// npm: imports stay as they are (Deno loads them). Run: npm run bundle (also in npm test).
// Check mode (--check) fails when a bundled.ts is out of date, so a stale paste is caught.
import { rolldown } from 'rolldown'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const FUNCS = ['nudge', 'widget']
const check = process.argv.includes('--check')
let stale = []

for (const name of FUNCS) {
  const input = join(ROOT, 'supabase/functions', name, 'index.ts')
  const bundle = await rolldown({ input, platform: 'neutral', external: [/^npm:/, /^jsr:/, /^https?:/], logLevel: 'silent' })
  const { output } = await bundle.generate({ format: 'esm' })
  const code =
    `// GENERATED by next/scripts/bundle-functions.mjs from supabase/functions/${name}/index.ts.\n` +
    `// Do not edit. Paste this whole file into the Supabase dashboard editor for "${name}".\n` +
    output[0].code
  const out = join(ROOT, 'supabase/functions', name, 'bundled.ts')
  if (check) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== code) stale.push(name)
  } else {
    writeFileSync(out, code)
    console.log(`bundled ${name}: ${code.length} bytes`)
  }
}
if (stale.length) {
  console.error(`bundle-functions: out of date: ${stale.join(', ')}. Run: npm run bundle`)
  process.exit(1)
}
